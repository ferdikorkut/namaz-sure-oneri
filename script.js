function drawerAc(sure) {
  const veri = SURE_METINLER[sure.no];
  if (!veri) return;
  document.getElementById('drawer-baslik').textContent = veri.baslik;
  const subtitle = document.getElementById('drawer-subtitle');
  subtitle.textContent = veri.subtitle || '';
  subtitle.style.display = veri.subtitle ? 'block' : 'none';
  const icerik = document.getElementById('drawer-icerik');
  icerik.innerHTML = veri.ayetler.map(a => {
    const cls = /^\d+-/.test(a) ? 'numarali' : '';
    return `<p class="${cls}">${a}</p>`;
  }).join('');
  document.getElementById('drawer-overlay').classList.add('acik');
  document.getElementById('drawer').classList.add('acik');
}

function drawerKapat() {
  document.getElementById('drawer-overlay').classList.remove('acik');
  document.getElementById('drawer').classList.remove('acik');
}

document.getElementById('drawer-overlay').addEventListener('click', drawerKapat);

function kartSwiped(kartEl, yenileFn, fark) {
  const slideOut = fark < 0 ? 'slide-out-left' : 'slide-out-right';
  const slideIn  = fark < 0 ? 'slide-in-left'  : 'slide-in-right';
  kartEl.classList.add(slideOut);
  setTimeout(() => {
    kartEl.classList.remove(slideOut);
    yenileFn();
    kartEl.classList.add(slideIn);
    setTimeout(() => kartEl.classList.remove(slideIn), 250);
  }, 250);
}

function swipeEkle(kartId, yenileFn) {
  const el = document.getElementById(kartId);
  let touchBasX = null;

  el.addEventListener('touchstart', (e) => {
    if (document.getElementById('drawer').classList.contains('acik')) return;
    touchBasX = e.touches[0].clientX;
  }, { passive: true });

  el.addEventListener('touchend', (e) => {
    if (touchBasX === null) return;
    const fark = e.changedTouches[0].clientX - touchBasX;
    touchBasX = null;
    if (Math.abs(fark) < 50) return;
    kartSwiped(el, yenileFn, fark);
  }, { passive: true });
}

